local root=arg[1]:gsub('/Scripts/model.lua$','')
local S=dofile(root..'/Scripts/shortcuts.lua')
local model=dofile(root..'/Scripts/model.lua')
assert(not S.parse('').quick and not S.parse('').slots,'missing config must not opt in')
local cfg=S.parse('QuickPick=true\nSlotHotkeys=true\nSlot1Key=Z\nSlot2Key=X\nSlot3Key=Z\nSlot4Key=Q\nSlot1Spell=USD_Test')
assert(cfg.quick and cfg.slots and cfg.keys[1]=='Z' and cfg.keys[2]=='X' and not cfg.keys[3] and not cfg.keys[4])
assert(#cfg.warnings==2 and cfg.ids[1]=='USD_Test')
local groups=model.catalogue({{id='USD_Test',name='Translated name',skill='Woodcutting',unlocked=true},{id='USD_Locked',name='Locked',skill='Agility'}})
local state=model.new(groups);local s=S.new(cfg,model)
assert(not s.edges({slot1=true},true).slot1,'first sample primes')
s.edges({},true);assert(s.slot(s.edges({slot1=true},true))==1)
assert(not s.slot(s.edges({slot1=true},true)),'hold is not a repeat')
s.edges({},true);s.edges({slot1=true},false)
assert(not s.slot(s.edges({slot1=true},true)),'menu-held key cannot cast on exit')
s.edges({},true);assert(not s.slot(s.edges({slot1=true,shortcutModifier=true},true)),'modifier combinations ignored')
assert(not s.slot(s.edges({slot1=true},true)),'modifier release cannot fire held key')
s.reset({})
assert(s.quick(state,s.edges({quick1=true,quick2=true},true),0)=='group' and state.group==1 and not state.spell)
assert(not s.quick(state,s.edges({quick1=true},true),.1),'held 1 cannot cast')
s.edges({},true);assert(s.quick(state,s.edges({quick1=true},true),.2)=='select')
assert(model.selection(state).id=='USD_Test')
s.reset({});s.quick(state,{quick12=true},1);assert(state.group==12)
assert(not s.quick(state,{quick6=true},2),'out of range spell does nothing')
s.quick(state,{quick1=true},6);assert(state.group==1 and s.stage=='spells','timeout selects a skill')
s.quick(state,{quick12=true},6.1,true);assert(state.group==12,'mouse/controller resets stage')
local gi,si=s.find(groups,'USD_Test');assert(gi==1 and si==1,'stable identity, not display name')
assert(not s.find(groups,'Translated name'))
-- Exercise real file writes, duplicate-line removal, unrelated settings, reload,
-- clearing and rollback when replacement fails. Nothing touches root/config.txt.
local path=os.tmpname();local f=assert(io.open(path,'w'))
f:write('# preserved\nEnabled=false\nQuickPick=true\nSlot1Spell=USD_Old\nSlot1Spell=USD_Older\nForeignSetting=keep\n');f:close()
assert(S.save(path,1,'USD_Test'));assert(S.load(path).ids[1]=='USD_Test')
f=assert(io.open(path));local text=f:read('a');f:close()
assert(text:find('# preserved',1,true) and text:find('ForeignSetting=keep',1,true) and text:find('Enabled=false',1,true))
assert(not text:find('USD_Old',1,true))
assert(S.save(path,1,nil) and not S.load(path).ids[1])
assert(not S.save(path,0,'USD_Test') and not S.save(path,1,'../../data'))
local rename=os.rename
os.rename=function(a,b)if a==path..'.shortcuts.tmp' then return nil,'injected replace failure' end;return rename(a,b)end
assert(not S.save(path,1,'USD_New'));os.rename=rename
assert(not S.load(path).ids[1],'failed replacement restores the original')
f=assert(io.open(path..'.shortcuts.bak','w'));f:write('recovery');f:close()
assert(not S.save(path,1,'USD_New'),'never overwrites an interrupted recovery backup')
os.remove(path);os.remove(path..'.shortcuts.bak')
print('PASS: opt-in config, key conflicts, edge/menu/modifier guards, quick-pick stages/timeout, stable identity, persistent assignments and rollback')
