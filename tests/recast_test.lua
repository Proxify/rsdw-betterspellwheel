-- Double-tap recast: plain-data parsing and timing (no engine).
local root=arg[1]:gsub('/Scripts/model.lua$','')
local R=dofile(root..'/Scripts/recast.lua')
local off=R.parse('')
assert(not off.enabled and off.window==.35 and not off.spell,'missing config must not opt in')
assert(R.parse('DoubleTapRecast=TRUE').enabled,'enable flag is case-insensitive')
local cfg=R.parse('DoubleTapRecast=true\nDoubleTapWindowMs=500\nDoubleTapSpell=Last')
assert(cfg.enabled and cfg.window==.5 and not cfg.spell and #cfg.warnings==0)
assert(R.parse('DoubleTapWindowMs=20').window==.15 and R.parse('DoubleTapWindowMs=9000').window==1,'window is clamped')
local bad=R.parse('DoubleTapWindowMs=fast\nDoubleTapSpell=Windstep')
assert(bad.window==.35 and not bad.spell and #bad.warnings==2,'invalid values are ignored and logged')
assert(R.parse('DoubleTapSpell=USD_Windstep').spell=='USD_Windstep')
assert(R.parse('  DoubleTapRecast = true  \r\n').enabled,'spaces and CRLF')
-- Timing: armed only by the native open, fresh press only, consumed once.
local r=R.new(cfg)
assert(not r.tapped(0,true),'not armed')
r.arm(10);assert(not r.tapped(10.1,false),'a held key is not a tap')
assert(r.tapped(10.4,true),'fresh press inside the window');assert(not r.tapped(10.45,true),'consumed: a third tap closes')
r.arm(20);assert(not r.tapped(20.51,true),'late press closes normally')
r.arm(30);r.disarm();assert(not r.tapped(30.1,true),'closing disarms')
local disabled=R.new(off);disabled.arm(0);assert(not disabled.tapped(.1,true),'disabled never arms')
-- Target: the fixed spell wins; otherwise the last accepted spell.
assert(r.target()==nil);r.remember('USD_Windstep');assert(r.target()=='USD_Windstep')
r.remember(nil);assert(r.target()=='USD_Windstep','non-IDs are ignored')
assert(R.new(R.parse('DoubleTapSpell=USD_Teleport'),'USD_Windstep').target()=='USD_Teleport')
assert(R.new(cfg,'USD_Kept').target()=='USD_Kept','previous generation seeds the last spell')
-- The shipped config keeps it OFF with the documented defaults.
local shipped=R.load(root..'/config.txt')
assert(not shipped.enabled and shipped.window==.35 and not shipped.spell and #shipped.warnings==0)
print('PASS: double-tap recast config defaults off, clamps/validates values; fresh-press timing, single use and spell target')
